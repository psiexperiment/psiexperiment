def test_strobed_ir_pipeline_detects_key():
    '''
    The keys drive the same processing chain as the IR sensors on a rig
    (cftscal.paradigms.ir_sensor.StrobedIR), so its edges match the keys.
    '''
    fs = 10000
    tone = ToneFactory(fs=fs, frequency=500, level=1)
    engine = KeyboardEngine(name='keyboard', fs=fs)
    channel = KeyboardAIChannel(name='np_contact', key='Space', parent=engine)
    engine.add_channel(channel)
    ao = KeyboardAOChannel(name='ir_emitter', parent=engine)
    engine.add_channel(ao)
    wavegen = ContinuousCallbackOutput(name='wavegen',
                                       callback=lambda n, _: tone.next(n))
    ao.add_output(wavegen)
    wavegen.active = True

    # Built as in StrobedIR, where each block is declared inside the last.
    events = []
    blocks = [
        DecimateTo(name='np_decimate', target_fs=4000),
        ExtractPower(name='np_raw', duration=0.05, frequency=500),
        AutoScale(name='np_analog', baseline=-1),
        Threshold(threshold=0.5, mode='<'),
        Edges(name='np_digital', debounce=2, detect='both'),
        Callback(function=lambda d: events.extend(
            d.events[['event', 'ts']].itertuples(index=False))),
    ]
    parent = channel
    for block in blocks:
        block.set_parent(parent)
        parent.add_input(block)
        parent = block
    engine.configure()

    engine.set_key('np_contact', True, ts=1.0)
    engine.set_key('np_contact', False, ts=2.0)
    for ts in np.arange(0.1, 3.05, 0.1):
        engine.generate(ts)

    assert [e for e, _ in events] == ['rising', 'falling']
    assert events[0][1] == pytest.approx(1.0, abs=0.1)
    assert events[1][1] == pytest.approx(2.0, abs=0.1)


def test_extract_power_duration_updates_fs():
    '''
    Changing the chunk duration after the chain is built (as StrobedIR does
    for a channel's settings) tells the inputs downstream of the new rate.
    '''
    engine = KeyboardEngine(name='keyboard', fs=10000)
    channel = KeyboardAIChannel(name='np_contact', key='Space', parent=engine)
    engine.add_channel(channel)
    power = ExtractPower(name='np_raw', duration=0.05, frequency=500)
    power.set_parent(channel)
    channel.add_input(power)
    scale = AutoScale(name='np_analog', baseline=-1)
    scale.set_parent(power)
    power.add_input(scale)

    rates = []
    scale.observe('fs', lambda e: rates.append(e['value']))
    assert scale.fs == pytest.approx(20)
    power.duration = 0.01
    assert scale.fs == pytest.approx(100)
    assert rates == [pytest.approx(100)]


