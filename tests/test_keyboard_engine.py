'''
Tests for the keyboard engine (psi.controller.engines.keyboard).

Samples are generated by calling `generate` with explicit timestamps rather
than from the engine's thread, so the tests are deterministic.
'''
import numpy as np
import pytest

from psiaudio.calibration import FlatCalibration
from psiaudio.stim import ToneFactory

from psi.controller.api import ContinuousCallbackOutput, HardwareAOChannel
from psi.controller.engines.keyboard import (
    KeyboardAIChannel, KeyboardAOChannel, KeyboardEngine, LoopbackAIChannel,
    make_key_filter, qt_key
)
from psi.controller.engines.null import NullEngine
from psi.controller.input import (
    AutoScale, Callback, DecimateTo, Edges, ExtractPower, Threshold
)


FS = 1000


def make_engine(emitter=None, clock=None, **kw):
    engine = KeyboardEngine(name='keyboard', fs=FS, **kw)
    if clock is not None:
        engine.clock = clock
    np_channel = KeyboardAIChannel(name='np_contact', key='Space',
                                   parent=engine)
    engine.add_channel(np_channel)
    resp_channel = KeyboardAIChannel(name='resp_contact_1', key='Right',
                                     held_level=0, parent=engine)
    engine.add_channel(resp_channel)
    if emitter is not None:
        ao = KeyboardAOChannel(name='ir_emitter', parent=engine)
        engine.add_channel(ao)
        output = ContinuousCallbackOutput(name='wavegen', callback=emitter)
        ao.add_output(output)
        output.active = True
    return engine


def record(channel):
    '''
    Collect the data passed to `channel`'s inputs.
    '''
    blocks = []
    channel.add_input(Callback(function=blocks.append))
    return blocks


def concat(blocks):
    for i, block in enumerate(blocks[1:]):
        assert block.s0 == blocks[i].s0 + blocks[i].shape[-1]
    return np.concatenate(blocks, axis=-1)[0]


def test_key_drops_level_while_held():
    engine = make_engine()
    np_data = record(engine.get_channel('np_contact'))
    resp_data = record(engine.get_channel('resp_contact_1'))
    engine.configure()

    engine.set_key('np_contact', True, ts=0.25)
    engine.generate(0.5)
    engine.set_key('np_contact', False, ts=0.75)
    engine.generate(1.0)

    data = concat(np_data)
    assert data.shape == (FS,)
    expected = np.ones(FS)
    expected[250:750] = 0.1
    np.testing.assert_array_equal(data, expected)
    # Other keys are unaffected.
    np.testing.assert_array_equal(concat(resp_data), np.ones(FS))


def test_inputs_read_back_emitter():
    engine = make_engine(emitter=lambda n, _: np.full(n, 2.0))
    np_data = record(engine.get_channel('np_contact'))
    resp_data = record(engine.get_channel('resp_contact_1'))
    engine.configure()

    engine.set_key('resp_contact_1', True, ts=0.5)
    engine.generate(1.0)
    np.testing.assert_array_equal(concat(np_data), np.full(FS, 2.0))
    expected = np.full(FS, 2.0)
    expected[500:] = 0
    np.testing.assert_array_equal(concat(resp_data), expected)


def test_press_after_block_is_kept_for_next_block():
    engine = make_engine()
    np_data = record(engine.get_channel('np_contact'))
    engine.configure()
    # Timestamped after the samples generated so far (e.g., a race between
    # the key and the generator).
    engine.set_key('np_contact', True, ts=0.6)
    engine.generate(0.5)
    assert np.all(concat(np_data) == 1)
    engine.generate(1.0)
    data = concat(np_data)
    assert np.all(data[:600] == 1)
    assert np.all(data[600:] == 0.1)


def test_repeated_press_and_release_keys():
    engine = make_engine()
    record(engine.get_channel('np_contact'))
    record(engine.get_channel('resp_contact_1'))
    engine.configure()
    engine.set_key('np_contact', True, ts=0.1)
    engine.set_key('np_contact', True, ts=0.2)
    engine.set_key('resp_contact_1', True, ts=0.3)
    assert len(engine._events) == 2

    engine.release_keys()
    assert not any(engine._pressed.values())
    assert [e[1:] for e in engine._events][-2:] == \
        [('np_contact', False), ('resp_contact_1', False)]


def test_unknown_channel_ignored():
    engine = make_engine()
    engine.configure()
    engine.set_key('nonexistent', True, ts=0.1)
    assert len(engine._events) == 0


def test_uses_clock_engine_time():
    class Clock:
        ts = 0.0

        def get_ts(self):
            return self.ts

    clock = Clock()
    engine = make_engine(clock=clock)
    np_data = record(engine.get_channel('np_contact'))
    engine.configure()

    # The clock has not started, so there is nothing to generate yet.
    engine.generate()
    assert np_data == []

    clock.ts = 0.4
    engine.set_key('np_contact', True)
    assert engine._events[-1][0] == 0.4
    clock.ts = 0.5
    engine.generate()
    data = concat(np_data)
    assert data.shape == (500,)
    assert np.all(data[400:] == 0.1)


def test_loopback_reads_back_source():
    sound = NullEngine(name='sound', buffer_size=10)
    speaker = HardwareAOChannel(name='speaker_1', fs=2 * FS,
                                calibration=FlatCalibration.as_attenuation(),
                                parent=sound)
    sound.add_channel(speaker)
    output = ContinuousCallbackOutput(
        name='stim', callback=lambda n, _: np.arange(n, dtype='double'))
    speaker.add_output(output)
    output.active = True

    engine = KeyboardEngine(name='keyboard', fs=FS, clock=sound)
    loopback = LoopbackAIChannel(name='loopback_1', source_name='speaker_1',
                                 parent=engine)
    engine.add_channel(loopback)
    assert loopback.fs == 2 * FS
    data = record(loopback)
    engine.configure()

    # The sound card writes ahead of what has been played.
    buffer = np.zeros(1500)
    speaker.get_samples(0, 1500, buffer)
    engine.generate(0.5)
    np.testing.assert_array_equal(concat(data), np.arange(1000))

    buffer = np.zeros(1500)
    speaker.get_samples(1500, 1500, buffer)
    engine.generate(1.0)
    expected = np.concatenate([np.arange(1500), np.arange(500)])
    np.testing.assert_array_equal(concat(data), expected)

    # Monitors are removed when the engine stops.
    engine.start()
    engine.stop()
    assert speaker.monitors == []


def test_strobed_ir_pipeline_detects_key():
    '''
    The keys drive the same processing chain as the IR sensors on a rig
    (cftscal.paradigms.ir_sensor.StrobedIR), so its edges match the keys.
    '''
    fs = 10000
    tone = ToneFactory(fs=fs, frequency=500, level=1)
    engine = KeyboardEngine(name='keyboard', fs=fs)
    channel = KeyboardAIChannel(name='np_contact', key='Space', parent=engine)
    engine.add_channel(channel)
    ao = KeyboardAOChannel(name='ir_emitter', parent=engine)
    engine.add_channel(ao)
    wavegen = ContinuousCallbackOutput(name='wavegen',
                                       callback=lambda n, _: tone.next(n))
    ao.add_output(wavegen)
    wavegen.active = True

    # Built as in StrobedIR, where each block is declared inside the last.
    events = []
    blocks = [
        DecimateTo(name='np_decimate', target_fs=4000),
        ExtractPower(name='np_raw', duration=0.05, frequency=500),
        AutoScale(name='np_analog', baseline=-1),
        Threshold(threshold=0.5, mode='<'),
        Edges(name='np_digital', debounce=2, detect='both'),
        Callback(function=lambda d: events.extend(
            d.events[['event', 'ts']].itertuples(index=False))),
    ]
    parent = channel
    for block in blocks:
        block.set_parent(parent)
        parent.add_input(block)
        parent = block
    engine.configure()

    engine.set_key('np_contact', True, ts=1.0)
    engine.set_key('np_contact', False, ts=2.0)
    for ts in np.arange(0.1, 3.05, 0.1):
        engine.generate(ts)

    assert [e for e, _ in events] == ['rising', 'falling']
    assert events[0][1] == pytest.approx(1.0, abs=0.1)
    assert events[1][1] == pytest.approx(2.0, abs=0.1)


def test_qt_key():
    from enaml.qt.QtCore import Qt
    assert qt_key('Space') == Qt.Key.Key_Space
    assert qt_key('J') == Qt.Key.Key_J
    with pytest.raises(ValueError, match='Unknown key'):
        qt_key('NotAKey')


def test_key_filter(app):
    from enaml.qt.QtCore import QEvent, Qt
    from enaml.qt.QtGui import QKeyEvent
    from enaml.qt.QtWidgets import QApplication, QLineEdit, QPushButton

    engine = make_engine()
    record(engine.get_channel('np_contact'))
    engine.configure()
    key_filter = make_key_filter(engine, {Qt.Key.Key_Space: 'np_contact'})

    def send(widget, kind, key=Qt.Key.Key_Space, repeat=False):
        event = QKeyEvent(kind, key, Qt.KeyboardModifier.NoModifier, '',
                          repeat)
        return key_filter.eventFilter(widget, event)

    button = QPushButton()
    assert send(button, QEvent.Type.KeyPress)
    assert engine._pressed['np_contact']
    # Repeats while the key is held are consumed but ignored.
    assert send(button, QEvent.Type.KeyPress, repeat=True)
    assert send(button, QEvent.Type.KeyRelease, repeat=True)
    assert engine._pressed['np_contact']
    assert send(button, QEvent.Type.KeyRelease)
    assert not engine._pressed['np_contact']
    # Keys that are not mapped are left alone.
    assert not send(button, QEvent.Type.KeyPress, key=Qt.Key.Key_A)

    # Losing focus releases the keys.
    send(button, QEvent.Type.KeyPress)
    key_filter.eventFilter(QApplication.instance(),
                           QEvent(QEvent.Type.ApplicationDeactivate))
    assert not engine._pressed['np_contact']

    # Typing into a field is not a key press.
    field = QLineEdit()
    field.show()
    field.setFocus()
    QApplication.processEvents()
    if QApplication.focusWidget() is field:
        assert not send(field, QEvent.Type.KeyPress)
        assert not engine._pressed['np_contact']
    field.close()


def test_thread_generates_samples():
    import time
    engine = make_engine()
    np_data = record(engine.get_channel('np_contact'))
    engine.configure()
    engine.start()
    time.sleep(0.2)
    engine.set_key('np_contact', True)
    time.sleep(0.2)
    engine.stop()
    data = concat(np_data)
    # Within a poll interval or two of real time.
    assert 0.35 * FS <= data.shape[-1] <= 0.45 * FS
    assert data[0] == 1
    assert data[-1] == 0.1
