def test_key_filter(app):
    from enaml.qt.QtCore import QEvent, Qt
    from enaml.qt.QtGui import QKeyEvent
    from enaml.qt.QtWidgets import QApplication, QLineEdit, QPushButton

    engine = make_engine()
    record(engine.get_channel('np_contact'))
    engine.configure()
    key_filter = make_key_filter(engine, {Qt.Key.Key_Space: 'np_contact'})

    def send(widget, kind, key=Qt.Key.Key_Space, repeat=False):
        event = QKeyEvent(kind, key, Qt.KeyboardModifier.NoModifier, '',
                          repeat)
        return key_filter.eventFilter(widget, event)

    button = QPushButton()
    assert send(button, QEvent.Type.KeyPress)
    assert engine._pressed['np_contact']
    # Repeats while the key is held are consumed but ignored.
    assert send(button, QEvent.Type.KeyPress, repeat=True)
    assert send(button, QEvent.Type.KeyRelease, repeat=True)
    assert engine._pressed['np_contact']
    assert send(button, QEvent.Type.KeyRelease)
    assert not engine._pressed['np_contact']
    # Keys that are not mapped are left alone.
    assert not send(button, QEvent.Type.KeyPress, key=Qt.Key.Key_A)

    # Losing focus releases the keys.
    send(button, QEvent.Type.KeyPress)
    key_filter.eventFilter(QApplication.instance(),
                           QEvent(QEvent.Type.ApplicationDeactivate))
    assert not engine._pressed['np_contact']

    # Typing into a field is not a key press.
    field = QLineEdit()
    field.show()
    field.setFocus()
    QApplication.processEvents()
    if QApplication.focusWidget() is field:
        assert not send(field, QEvent.Type.KeyPress)
        assert not engine._pressed['np_contact']
    field.close()


def test_key_shared_by_channels(app):
    '''
    Channels that share a key are all driven by it, as when a rig makes one
    sensor available under two names.
    '''
    from enaml.qt.QtCore import QEvent, Qt
    from enaml.qt.QtGui import QKeyEvent
    from enaml.qt.QtWidgets import QPushButton

    engine = make_engine()
    shared = KeyboardAIChannel(name='reward_contact', key='Right',
                               parent=engine)
    engine.add_channel(shared)
    for name in ('resp_contact_1', 'reward_contact'):
        record(engine.get_channel(name))
    engine.configure()
    engine._install_key_filter()
    try:
        event = QKeyEvent(QEvent.Type.KeyPress, Qt.Key.Key_Right,
                          Qt.KeyboardModifier.NoModifier, '', False)
        assert engine._key_filter.eventFilter(QPushButton(), event)
        assert engine._pressed['resp_contact_1']
        assert engine._pressed['reward_contact']
    finally:
        engine._remove_key_filter()


def test_thread_generates_samples():
    import time
    engine = make_engine()
    np_data = record(engine.get_channel('np_contact'))
    engine.configure()
    engine.start()
    time.sleep(0.2)
    engine.set_key('np_contact', True)
    time.sleep(0.2)
    engine.stop()
    engine._thread.join(1)
    data = concat(np_data)
    # Within a poll interval or two of real time.
    assert 0.35 * FS <= data.shape[-1] <= 0.45 * FS
    assert data[0] == 1
    assert data[-1] == 0.1


def test_stop_does_not_wait_on_input_callbacks():
    '''
    An input's callback can wait on the thread that stops the engine (e.g., a
    DPOAE's action waits on the control dispatcher, which is the thread
    stopping the engines). Stopping must not wait for that callback.
    '''
    import threading
    engine = make_engine()
    stopped = threading.Event()
    entered = threading.Event()

    def wait_for_stop(data):
        entered.set()
        stopped.wait(5)

    engine.get_channel('np_contact').add_input(Callback(function=wait_for_stop))
    engine.configure()
    engine.start()
    assert entered.wait(2)
    stopper = threading.Thread(target=engine.stop)
    stopper.start()
    stopper.join(2)
    assert not stopper.is_alive(), 'stop() waited on the input callback'
    stopped.set()
    engine._thread.join(2)
    assert not engine._thread.is_alive()


def test_loopback_sync_start():
    '''
    Calibrations (`psi.controller.calibration.acquire`) sync each input with
    the output they play. A loopback is in sync with its clock's outputs.
    '''
    sound = NullEngine(name='sound', buffer_size=10)
    speaker, = make_speakers(sound, None)
    engine = KeyboardEngine(name='keyboard', fs=FS, clock=sound)
    loopback = LoopbackAIChannel(name='microphone', source_name='speaker_1',
                                 parent=engine)
    engine.add_channel(loopback)
    loopback.sync_start(speaker)

    other = NullEngine(name='other', buffer_size=10)
    other_speaker, = make_speakers(other, None)
    with pytest.raises(ValueError, match='synced'):
        loopback.sync_start(other_speaker)


def test_cloned_engine_keeps_clock():
    '''
    Calibrations run on clones of the engines. A cloned keyboard engine must
    read back the cloned sound card's outputs, which are the ones that play.
    '''
    from psi.controller.calibration.acquire import clone_engines
    sound = NullEngine(name='sound', buffer_size=10)
    make_speakers(sound, None)
    engine = KeyboardEngine(name='keyboard', fs=FS, clock=sound)
    loopback = LoopbackAIChannel(name='microphone', source_name='speaker_1',
                                 parent=engine)
    engine.add_channel(loopback)

    sound_clone, engine_clone = clone_engines([sound, engine])
    assert engine_clone.clock is sound_clone
    assert engine_clone.get_channel('microphone').source is \
        sound_clone.get_channel('speaker_1')
