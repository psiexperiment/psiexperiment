'''
Tests for the keyboard engine (psi.controller.engines.keyboard).

Samples are generated by calling `generate` with explicit timestamps rather
than from the engine's thread, so the tests are deterministic.
'''
import numpy as np
import pytest

from psiaudio.calibration import FlatCalibration
from psiaudio.stim import ToneFactory

from psi.controller.api import (
    ContinuousCallbackOutput, HardwareAOChannel, TimedTrigger
)
from psi.controller.engines.keyboard import (
    KeyboardAIChannel, KeyboardAOChannel, KeyboardDOChannel, KeyboardEngine,
    LoopbackAIChannel, make_key_filter, qt_key
)
from psi.controller.engines.null import NullEngine
from psi.controller.input import (
    AutoScale, Callback, DecimateTo, Edges, ExtractPower, Threshold
)


FS = 1000


def make_engine(emitter=None, clock=None, **kw):
    engine = KeyboardEngine(name='keyboard', fs=FS, **kw)
    if clock is not None:
        engine.clock = clock
    np_channel = KeyboardAIChannel(name='np_contact', key='Space',
                                   parent=engine)
    engine.add_channel(np_channel)
    resp_channel = KeyboardAIChannel(name='resp_contact_1', key='Right',
                                     held_level=0, parent=engine)
    engine.add_channel(resp_channel)
    if emitter is not None:
        ao = KeyboardAOChannel(name='ir_emitter', parent=engine)
        engine.add_channel(ao)
        output = ContinuousCallbackOutput(name='wavegen', callback=emitter)
        ao.add_output(output)
        output.active = True
    return engine


def record(channel):
    '''
    Collect the data passed to `channel`'s inputs.
    '''
    blocks = []
    channel.add_input(Callback(function=blocks.append))
    return blocks


def concat(blocks):
    for i, block in enumerate(blocks[1:]):
        assert block.s0 == blocks[i].s0 + blocks[i].shape[-1]
    return np.concatenate(blocks, axis=-1)[0]


def test_key_drops_level_while_held():
    engine = make_engine()
    np_data = record(engine.get_channel('np_contact'))
    resp_data = record(engine.get_channel('resp_contact_1'))
    engine.configure()

    engine.set_key('np_contact', True, ts=0.25)
    engine.generate(0.5)
    engine.set_key('np_contact', False, ts=0.75)
    engine.generate(1.0)

    data = concat(np_data)
    assert data.shape == (FS,)
    expected = np.ones(FS)
    expected[250:750] = 0.1
    np.testing.assert_array_equal(data, expected)
    # Other keys are unaffected.
    np.testing.assert_array_equal(concat(resp_data), np.ones(FS))


def test_inputs_read_back_emitter():
    engine = make_engine(emitter=lambda n, _: np.full(n, 2.0))
    np_data = record(engine.get_channel('np_contact'))
    resp_data = record(engine.get_channel('resp_contact_1'))
    engine.configure()

    engine.set_key('resp_contact_1', True, ts=0.5)
    engine.generate(1.0)
    np.testing.assert_array_equal(concat(np_data), np.full(FS, 2.0))
    expected = np.full(FS, 2.0)
    expected[500:] = 0
    np.testing.assert_array_equal(concat(resp_data), expected)


def test_press_after_block_is_kept_for_next_block():
    engine = make_engine()
    np_data = record(engine.get_channel('np_contact'))
    engine.configure()
    # Timestamped after the samples generated so far (e.g., a race between
    # the key and the generator).
    engine.set_key('np_contact', True, ts=0.6)
    engine.generate(0.5)
    assert np.all(concat(np_data) == 1)
    engine.generate(1.0)
    data = concat(np_data)
    assert np.all(data[:600] == 1)
    assert np.all(data[600:] == 0.1)


def test_repeated_press_and_release_keys():
    engine = make_engine()
    record(engine.get_channel('np_contact'))
    record(engine.get_channel('resp_contact_1'))
    engine.configure()
    engine.set_key('np_contact', True, ts=0.1)
    engine.set_key('np_contact', True, ts=0.2)
    engine.set_key('resp_contact_1', True, ts=0.3)
    assert len(engine._events) == 2

    engine.release_keys()
    assert not any(engine._pressed.values())
    assert [e[1:] for e in engine._events][-2:] == \
        [('np_contact', False), ('resp_contact_1', False)]


def test_unknown_channel_ignored():
    engine = make_engine()
    engine.configure()
    engine.set_key('nonexistent', True, ts=0.1)
    assert len(engine._events) == 0


def test_uses_clock_engine_time():
    class Clock:
        ts = 0.0

        def get_ts(self):
            return self.ts

        def in_use(self):
            return True

    clock = Clock()
    engine = make_engine(clock=clock)
    np_data = record(engine.get_channel('np_contact'))
    engine.configure()

    # The clock has not started, so there is nothing to generate yet.
    engine.generate()
    assert np_data == []

    clock.ts = 0.4
    engine.set_key('np_contact', True)
    assert engine._events[-1][0] == 0.4
    clock.ts = 0.5
    engine.generate()
    data = concat(np_data)
    assert data.shape == (500,)
    assert np.all(data[400:] == 0.1)


def test_keeps_own_time_if_clock_not_in_use():
    # E.g., a paradigm that only monitors a loopback plays nothing on the
    # sound card, so it is never started; the keyboard engine keeps its own
    # time (and becomes the master engine).
    sound = NullEngine(name='sound', buffer_size=10)
    engine = make_engine(clock=sound)
    engine.configure()
    assert engine.get_ts() == 0.0
    engine.start()
    try:
        assert engine.get_ts() > 0
    finally:
        engine.stop()


def test_loopback_reads_back_source():
    sound = NullEngine(name='sound', buffer_size=10)
    speaker = HardwareAOChannel(name='speaker_1', fs=2 * FS,
                                calibration=FlatCalibration.as_attenuation(),
                                parent=sound)
    sound.add_channel(speaker)
    output = ContinuousCallbackOutput(
        name='stim', callback=lambda n, _: np.arange(n, dtype='double'))
    speaker.add_output(output)
    output.active = True

    engine = KeyboardEngine(name='keyboard', fs=FS, clock=sound)
    loopback = LoopbackAIChannel(name='loopback_1', source_name='speaker_1',
                                 parent=engine)
    engine.add_channel(loopback)
    assert loopback.fs == 2 * FS
    data = record(loopback)
    engine.configure()

    # The sound card writes ahead of what has been played.
    buffer = np.zeros(1500)
    speaker.get_samples(0, 1500, buffer)
    engine.generate(0.5)
    np.testing.assert_array_equal(concat(data), np.arange(1000))

    buffer = np.zeros(1500)
    speaker.get_samples(1500, 1500, buffer)
    engine.generate(1.0)
    expected = np.concatenate([np.arange(1500), np.arange(500)])
    np.testing.assert_array_equal(concat(data), expected)

    # Monitors are removed when the engine stops.
    engine.start()
    engine.stop()
    assert speaker.monitors == []


def test_loopback_reads_back_timed_trigger():
    '''
    A TTL scheduled on a hardware-timed digital output on the keyboard engine
    (e.g., a sync pulse) is read back by a loopback of it.
    '''
    sound = NullEngine(name='sound', buffer_size=10)
    engine = KeyboardEngine(name='keyboard', fs=FS, clock=sound)
    sync = KeyboardDOChannel(name='sync_trigger', parent=engine)
    engine.add_channel(sync)
    trigger = TimedTrigger(name='sync_trigger')
    sync.add_output(trigger)
    loopback = LoopbackAIChannel(name='sync_monitor',
                                 source_name='sync_trigger', parent=engine)
    engine.add_channel(loopback)
    assert sync.fs == FS
    assert loopback.fs == FS
    data = record(loopback)
    engine.configure()

    trigger.trigger(0.25, 0.1)
    engine.generate(0.2)
    engine.generate(0.5)
    expected = np.zeros(500)
    expected[250:350] = 1
    np.testing.assert_array_equal(concat(data), expected)


def make_speakers(sound, *callbacks):
    '''
    One output channel on `sound` per callback, playing it (None leaves the
    channel unused).
    '''
    speakers = []
    for i, callback in enumerate(callbacks):
        speaker = HardwareAOChannel(
            name=f'speaker_{i + 1}', fs=FS,
            calibration=FlatCalibration.as_attenuation(), parent=sound)
        sound.add_channel(speaker)
        if callback is not None:
            output = ContinuousCallbackOutput(name=f'stim_{i + 1}',
                                              callback=callback)
            speaker.add_output(output)
            output.active = True
        speakers.append(speaker)
    return speakers


def test_loopback_sums_sources():
    '''
    A loopback of several outputs (e.g., a starship's microphone) reads back
    their sum, and only as far as all of them have been written.
    '''
    sound = NullEngine(name='sound', buffer_size=10)
    s1, s2 = make_speakers(
        sound,
        lambda n, _: np.ones(n),
        lambda n, _: np.full(n, 2.0),
    )
    engine = KeyboardEngine(name='keyboard', fs=FS, clock=sound)
    loopback = LoopbackAIChannel(name='microphone',
                                 source_names=['speaker_1', 'speaker_2'],
                                 parent=engine)
    engine.add_channel(loopback)
    assert loopback.sources == [s1, s2]
    data = record(loopback)
    engine.configure()

    s1.get_samples(0, 500, np.zeros(500))
    s2.get_samples(0, 300, np.zeros(300))
    engine.generate(1.0)
    np.testing.assert_array_equal(concat(data), np.full(300, 3.0))

    # Speaker 2 is now ahead, so speaker 1 holds it back.
    s2.get_samples(300, 400, np.zeros(400))
    engine.generate(1.0)
    np.testing.assert_array_equal(concat(data), np.full(500, 3.0))

    s1.get_samples(500, 500, np.zeros(500))
    engine.generate(1.0)
    np.testing.assert_array_equal(concat(data), np.full(700, 3.0))

    engine.start()
    engine.stop()
    assert s1.monitors == [] and s2.monitors == []


